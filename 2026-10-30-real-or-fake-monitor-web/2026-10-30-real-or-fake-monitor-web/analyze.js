// Real or Fake Monitor: server function that sends one menu photo to Claude and returns a JSON verdict.
// The API key lives only in the Vercel environment variable ANTHROPIC_API_KEY, never in the page.

const MODEL = process.env.ANTHROPIC_MODEL || "claude-sonnet-5-5";
const PER_IP_PER_DAY = Number(process.env.PER_IP_PER_DAY || 15);
const TOTAL_PER_DAY = Number(process.env.TOTAL_PER_DAY || 300);
const MAX_BASE64 = 2_000_000; // about 1.5 MB image

// Best-effort counters. They reset when Vercel restarts the function,
// so the spend limit in the Anthropic Console stays the real safety cap.
let day = "";
let total = 0;
const perIp = new Map();

function allow(ip) {
  const today = new Date().toISOString().slice(0, 10);
  if (today !== day) { day = today; total = 0; perIp.clear(); }
  const used = perIp.get(ip) || 0;
  if (used >= PER_IP_PER_DAY || total >= TOTAL_PER_DAY) return false;
  perIp.set(ip, used + 1);
  total += 1;
  return true;
}

function buildPrompt(lang, meta) {
  const language = lang === "en" ? "English" : "Bahasa Indonesia";
  let metaLine = "none (normal for screenshots)";
  if (meta && meta.kind === "ai") metaLine = "official AI-generated marker present";
  else if (meta && meta.kind === "c2pa") metaLine = "Content Credentials present";
  else if (meta && typeof meta.cam === "string" && meta.cam) metaLine = "camera make/model: " + meta.cam.slice(0, 60);

  return `You are a visual-literacy assistant inside a student research tool about AI-generated menu visuals used by Indonesian food stalls (UMKM), food courts and delivery apps.
The attached image may be: a photo of a dish on a table, a phone photo of a printed menu board, poster, light box or vinyl banner, or a screenshot of a delivery app.
Judge the WHOLE visual the buyer sees: the food images, the people, mascots and animals, the text and the layout. If the image is a photo of a poster, banner or screen, judge the artwork printed on it, not the act of photographing it.

Classify as "real" or "fake". There is no third option.
"real" (level 1): an honest photo of the actual dish, or a menu whose food pictures are genuine photographs of that dish. Normal brightness, color, cropping and tidy plating are still real.
"fake" level 2: real photography that was manipulated beyond normal adjustment (composited, portion or shape altered, pasted steam or garnish, swapped background).
"fake" level 3: food, people or scenes generated by AI.

Signs of AI-generated menu visuals, learned from many real examples in Indonesian food courts:
FOOD: every item rendered at the same angle and lighting in a perfect grid; identical cross-sections; rice grains like uniform beads or pearls; fries, coins or mochi that are all exactly the same; fruit as perfect spheres; frozen mid-air chocolate or sauce pours; floating leaves, splashes and ingredients; waxy, glossy, airbrushed surfaces with no crumbs, smears or uneven browning; steam and bokeh that look painted.
PEOPLE AND ANIMALS: plastic or airbrushed skin; exaggerated grins and winks; hands with wrong finger count, merged fingers or odd nails; hands holding plates at impossible angles; uncanny cats or mascots.
TEXT AND LAYOUT: misspellings or doubled letters (for example "Dubay", "Enakk"); decorative Japanese, Korean or Chinese text that does not fit the stall; garbled small print; generic AI slogans ("Premium Taste, Made with Passion", "Made with love", "Fresh ingredients") with rows of round icon badges; the same template, props and backgrounds repeated across panels; brand logos or jars that are slightly wrong.
CONTEXT: since 2024 many Indonesian stalls print AI-generated posters. A highly polished, studio-like poster for a small stall with no sign of real photography is more likely fake than real.

Rules:
1. Answer "fake" if you can name at least one concrete cue from the list above, in the food, people or text. List the strongest cues in markers.
2. Answer "real" only when the food looks like genuine photography (natural imperfections, real plates and tables, lighting consistent with a real place) and there is no AI cue in the people or text.
3. Camera metadata only proves the photo was taken with a phone. If the image shows a poster, banner, menu board or screen, ignore the metadata. Use it as a hint toward "real" only for a direct photo of a dish on a table.
File metadata found by the page: ${metaLine}.
Reply with only one JSON object, all text values in ${language}, short and plain:
{"is_food":true,"verdict":"fake|real","confidence":"low|medium|high","level":1,"markers":[{"label":"2 to 4 words naming the cue","x":0,"y":0}],"reason":"one or two sentences naming what you see","swap_test":"one sentence: could any other stall use this exact photo without anyone noticing, and why","buyer_tip":"one sentence","owner_tip":"one sentence"}
markers: for "fake" give 1 to 4 concrete cues (they can point at food, a face, a hand or a piece of text); for "real" give 0 to 3 cues that show it is genuine (for example "uap alami", "remah di meja"); x and y are percent positions (0 to 100) of each cue on the image. If the image shows no food, set is_food to false and keep other fields brief.`;
}

function parseJson(raw) {
  const text = String(raw || "").replace(/```(?:json)?/gi, "").replace(/[“”]/g, '"').trim();
  try { return JSON.parse(text); } catch (e) {}
  // Try every balanced {...} block and keep the first one that looks like our answer.
  for (let start = text.indexOf("{"); start >= 0; start = text.indexOf("{", start + 1)) {
    let depth = 0, inStr = false, esc = false;
    for (let i = start; i < text.length; i++) {
      const c = text[i];
      if (inStr) { if (esc) esc = false; else if (c === "\\") esc = true; else if (c === '"') inStr = false; continue; }
      if (c === '"') inStr = true;
      else if (c === "{") depth++;
      else if (c === "}") {
        depth--;
        if (depth === 0) {
          try {
            const obj = JSON.parse(text.slice(start, i + 1));
            if (obj && (obj.verdict || obj.is_food !== undefined)) return obj;
          } catch (e) {}
          break;
        }
      }
    }
  }
  return null;
}

function clean(d) {
  const s = (v, n) => String(v || "").slice(0, n);
  return {
    is_food: d.is_food !== false,
    verdict: d.verdict === "fake" ? "fake" : "real",
    confidence: ["low", "medium", "high"].includes(d.confidence) ? d.confidence : "medium",
    level: d.verdict === "fake" ? (Number(d.level) === 3 ? 3 : 2) : 1,
    markers: (Array.isArray(d.markers) ? d.markers : []).slice(0, 4).map(m => ({
      label: s(m && m.label, 40),
      x: Math.max(0, Math.min(100, Number(m && m.x) || 50)),
      y: Math.max(0, Math.min(100, Number(m && m.y) || 50)),
    })),
    reason: s(d.reason, 400),
    swap_test: s(d.swap_test, 300),
    buyer_tip: s(d.buyer_tip, 250),
    owner_tip: s(d.owner_tip, 250),
  };
}

module.exports = async function handler(req, res) {
  if (req.method !== "POST") return res.status(405).json({ error: "method" });
  if (!process.env.ANTHROPIC_API_KEY) return res.status(500).json({ error: "missing key" });

  const body = typeof req.body === "string" ? JSON.parse(req.body || "{}") : (req.body || {});
  const image = typeof body.image === "string" ? body.image : "";
  if (!image || image.length > MAX_BASE64 || !/^[A-Za-z0-9+/=]+$/.test(image)) {
    return res.status(400).json({ error: "image" });
  }

  const ip = String(req.headers["x-forwarded-for"] || "").split(",")[0].trim() || "unknown";
  if (!allow(ip)) return res.status(429).json({ error: "limit" });

  try {
    const r = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "content-type": "application/json",
        "x-api-key": process.env.ANTHROPIC_API_KEY,
        "anthropic-version": "2023-06-01",
      },
      body: JSON.stringify({
        model: MODEL,
        max_tokens: 1500,
        messages: [{
          role: "user",
          content: [
            { type: "image", source: { type: "base64", media_type: "image/jpeg", data: image } },
            { type: "text", text: buildPrompt(body.lang, body.meta) },
          ],
        }],
      }),
    });
    if (!r.ok) {
      console.error("anthropic", r.status, (await r.text()).slice(0, 300));
      return res.status(502).json({ error: "upstream" });
    }
    const out = await r.json();
    const text = (out.content || []).filter(c => c.type === "text").map(c => c.text).join("");
    const data = parseJson(text);
    if (!data) {
      console.error("parse", out.stop_reason, text.slice(0, 500));
      return res.status(502).json({ error: "parse", stop: out.stop_reason || "", raw: text.slice(0, 500) });
    }
    return res.status(200).json(clean(data));
  } catch (e) {
    console.error(e);
    return res.status(502).json({ error: "network" });
  }
};
